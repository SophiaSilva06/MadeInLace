    CONSTRAINT CK_VARIACAO_CUSTO CHECK (CUSTO >= 0),
    CONSTRAINT CK_VARIACAO_PRECO CHECK (PRECO > 0),
    CONSTRAINT CK_VARIACAO_PROMOCAO CHECK (PORCENTAGEM_PROMOCAO BETWEEN 0 AND 100)
