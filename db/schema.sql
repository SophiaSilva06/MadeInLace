        REFERENCES ITEM_VENDA (ID) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT CK_AVALIACAO_NOTA CHECK (NOTA BETWEEN 1 AND 5)
) ENGINE=InnoDB;

