    CONSTRAINT FK_HIST_STATUS_VENDA_STATUS FOREIGN KEY (FK_STATUS_VENDA)
        REFERENCES STATUS_VENDA (ID) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

